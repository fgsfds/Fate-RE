"""Strict compiled-C match and isolated behavior check for FATE's list removal."""
import argparse
import hashlib
import json
import struct
from pathlib import Path
from check_start_hook import EXPECTED
from le_fixups import read_le_fixups
from verify_c_leaf import bind_leaf_details, verify_leaf_relocations

ADDRESS, SIZE = 0x10f9f, 84
DATA = {'_listed_sprite_count': 0x2be8, '_listed_sprites': 0x6fcbc}
FUNCTIONS = {'remove_engine_sprite_': 0x50a09}


def bind(blob, loaded=False):
    data = {name: value + (0x80000 if loaded else 0) for name, value in DATA.items()}
    return bind_leaf_details(blob, 'remove_listed_sprite_', data,
                             address=ADDRESS, functions=FUNCTIONS)


def behavior(blob):
    from unicorn import Uc, UC_ARCH_X86, UC_MODE_32, UC_HOOK_CODE
    from unicorn.x86_const import (UC_X86_REG_EAX, UC_X86_REG_EBX,
        UC_X86_REG_ECX, UC_X86_REG_EDX, UC_X86_REG_EDI,
        UC_X86_REG_ESP, UC_X86_REG_EIP)
    code, _ = bind(blob, loaded=True)
    cases = [('empty', [], 1), ('missing', [2, 3, 4], 1),
             ('first', [1, 2, 3], 1), ('last', [2, 3, 1], 1),
             ('middle', [2, 1, 3], 1), ('single', [1], 1),
             ('duplicates', [1, 1, 1], 1), ('negative_id', [-1, 2], -1)]
    results = []
    for name, values, target in cases:
        expected = [-1234] + values[:]
        count, i = len(values), 1
        while i <= count:
            if expected[i] == target:
                expected[i] = expected[count]
                count -= 1
            i += 1
        for return_value in (0, 0xffffffff):
            uc = Uc(UC_ARCH_X86, UC_MODE_32)
            uc.mem_map(0, 0x400000)
            uc.mem_write(ADDRESS, code)
            uc.mem_write(0x82be8, struct.pack('<h', len(values)))
            uc.mem_write(0xefcbc, struct.pack('<' + 'h' * (len(values) + 1), -1234, *values))
            uc.mem_write(0x3ff000, struct.pack('<I', 0x3fff00))
            uc.reg_write(UC_X86_REG_ESP, 0x3ff000)
            uc.reg_write(UC_X86_REG_EAX, target & 0xffff)
            saved = (UC_X86_REG_EBX, UC_X86_REG_ECX, UC_X86_REG_EDX, UC_X86_REG_EDI)
            for reg in saved:
                uc.reg_write(reg, 0x12345678)
            calls = []
            def hook(machine, address, size, user):
                if address != 0x50a09:
                    return
                calls.append(machine.reg_read(UC_X86_REG_EAX))
                machine.reg_write(UC_X86_REG_EAX, return_value)
                esp = machine.reg_read(UC_X86_REG_ESP)
                ret = struct.unpack('<I', machine.mem_read(esp, 4))[0]
                machine.reg_write(UC_X86_REG_ESP, esp + 4)
                machine.reg_write(UC_X86_REG_EIP, ret)
            uc.hook_add(UC_HOOK_CODE, hook)
            uc.emu_start(ADDRESS, 0x3fff00, count=10000)
            assert uc.reg_read(UC_X86_REG_EIP) == 0x3fff00
            assert uc.reg_read(UC_X86_REG_ESP) == 0x3ff004
            assert all(uc.reg_read(reg) == 0x12345678 for reg in saved)
            assert calls == [target & 0xffffffff]
            assert struct.unpack('<h', uc.mem_read(0x82be8, 2))[0] == count
            assert bytes(uc.mem_read(0xefcbc, len(expected) * 2)) == struct.pack('<' + 'h' * len(expected), *expected)
        results.append(dict(case=name, remaining=count, full_list_after=expected[1:]))
    return results


def verify(executable, obj):
    exe, blob = Path(executable).read_bytes(), Path(obj).read_bytes()
    if hashlib.sha256(exe).hexdigest() != EXPECTED:
        raise ValueError('Unsupported executable hash')
    code, refs = bind(blob)
    if code != exe[ADDRESS + 0x25600:ADDRESS + 0x25600 + SIZE]:
        raise ValueError(f'Compiled code mismatch ({len(code)} generated bytes, {SIZE} target)')
    verify_leaf_relocations(code, refs, read_le_fixups(exe)['pointers'], ADDRESS)
    return dict(executable_sha256=EXPECTED, object_sha256=hashlib.sha256(blob).hexdigest(),
                entry=hex(ADDRESS), end_exclusive=hex(ADDRESS + SIZE), bytes=SIZE,
                exact_code=True, le_data_pointer_count=len(refs),
                data_bindings={key: hex(value) for key, value in DATA.items()},
                call_bindings={key: hex(value) for key, value in FUNCTIONS.items()},
                compiled_source_cases=behavior(blob), callee_returns_tested=[0, -1],
                external_callee_stubbed=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('executable', type=Path)
    parser.add_argument('object', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    result = verify(args.executable, args.object)
    if args.output:
        args.output.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(f"PASS: {SIZE} exact bytes, {result['le_data_pointer_count']} LE targets, 1 call binding, 16 compiled-source fixtures")
